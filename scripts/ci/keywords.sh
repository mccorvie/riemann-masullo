#!/usr/bin/env bash
# The list of tokens that can begin a Lean command, which scripts/ci/plain_proof.py reads.
#
#   scripts/ci/keywords.sh            print the list for the library as it is built now
#   scripts/ci/keywords.sh --check    fail if scripts/ci/command_keywords.txt is missing tokens
#   scripts/ci/keywords.sh --write    rewrite scripts/ci/command_keywords.txt (including Mathlib)
#
# The list needs updating when Mathlib or the toolchain is bumped, or when the library declares
# a new command. Extra tokens already listed (for unused Mathlib commands) are harmless for
# plain_proof.py, so --check requires only that every reachable token is listed.
# Run `lake build` first; this does not build anything.
set -euo pipefail
cd "$(dirname "$0")/../.."
list=scripts/ci/command_keywords.txt
modules=$(find RiemannMasullo -name '*.lean' | sort | sed 's#/#.#g; s#\.lean$##')
case ${1:-} in
  --check)
    # shellcheck disable=SC2086
    new=$(lake env lean --run scripts/ci/CommandKeywords.lean $modules)
    [ -n "$new" ] || { echo "CommandKeywords.lean produced no output" >&2; exit 1; }
    missing=$(LC_ALL=C comm -23 <(printf '%s\n' "$new" | LC_ALL=C sort -u) <(grep -v '^#' "$list" | LC_ALL=C sort -u))
    if [ -n "$missing" ]; then
      echo "scripts/ci/command_keywords.txt is missing tokens from the built library:" >&2
      printf '%s\n' "$missing" | head -n 40 >&2
      echo "Read what changed, then run scripts/ci/keywords.sh --write and commit the result." >&2
      exit 1
    fi
    echo "command keywords: up to date ($(grep -c '^command ' "$list") tokens)" ;;
  --write)
    # Include Mathlib so dropping an unused `import Mathlib` does not shrink the list and break
    # later pull requests or historical replays that import other Mathlib command modules.
    # shellcheck disable=SC2086
    new=$(lake env lean --run scripts/ci/CommandKeywords.lean Mathlib $modules)
    [ -n "$new" ] || { echo "CommandKeywords.lean produced no output" >&2; exit 1; }
    { echo "# Tokens that can begin a Lean command in this project, and word endings of other tokens."
      echo "# Generated by scripts/ci/keywords.sh --write; read by scripts/ci/plain_proof.py."
      printf '%s\n' "$new"; } >"$list"
    echo "wrote $list" ;;
  *)
    # shellcheck disable=SC2086
    lake env lean --run scripts/ci/CommandKeywords.lean $modules ;;
esac
